const cellOf = (ids) => {
  if (!ids || !ids.length) return '<div class="cell empty"><span>空缺</span></div>';
  const rows = ids
    .map((id) => {
      const h = byId[id];
      const pic = artUrl(h.art);
      const thumb = pic
        ? `<img class="mrow__pic" src="${pic}" alt="" draggable="false">`
        : `<span class="mrow__pic mrow__pic--ph" style="--c:${h.c}">${h.name.slice(0, 1)}</span>`;
      const dot = h.state === 'live' ? 'live' : h.ver ? 'ver' : 'plan';
      return `<a class="mrow" data-hero="${h.id}" style="--c:${h.c}">${thumb}<b>${h.name}</b><i class="mdot ${dot}" title="${h.state === 'live' ? '已上线' : h.ver ? `设计 V${h.ver}` : '待设计'}"></i></a>`;
    })
    .join('');
  const anyLive = ids.some((id) => byId[id].state === 'live');
  return `<div class="cell ${anyLive ? 'live' : 'plan'}" style="--c:${byId[ids[0]].c}">${rows}</div>`;
};

