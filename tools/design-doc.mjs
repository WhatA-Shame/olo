let biconSeq = 0;
const bicon = (id, cls = 'bico') => {
  const svg = BUFF_ICONS[id] || NEW_ICONS[id];
  if (!svg) return '';
  // 同一个图标会在 Buff 页和公式页各出现一次，渐变 id 必须各自唯一，
  // 否则 url(#id) 会命中另一份（可能在 display:none 的标签页里）导致整枚图标画不出来。
  const n = ++biconSeq;
  const uniq = svg
    .replace(/id="([^"]+)"/g, (m, name) => `id="${name}-${n}"`)
    .replace(/url\(#([^)]+)\)/g, (m, name) => `url(#${name}-${n})`);
  return uniq.replace(/class="sf-ico[^"]*"/, (m) => (m.includes(cls) ? m : m.replace(/"$/, ` ${cls}"`)));
};

