const PORTRAIT_ALIAS = { doll: 'mannequin', boxman: 'box', panyue: 'stagbeetle', yeque: 'blackcat', xingli: 'tiandongbao' };
const artCache = new Map();
function artUrl(id) {
  if (!id) return null;
  if (artCache.has(id)) return artCache.get(id);
  const styled = path.join(PORTRAIT_DIR, (PORTRAIT_ALIAS[id] || id) + '.webp');
  const p = fs.existsSync(styled) ? styled : path.join(ART_DIR, id + '.webp');
  if (!fs.existsSync(p)) return null;
  const u = 'data:image/webp;base64,' + fs.readFileSync(p).toString('base64');
  artCache.set(id, u);
  return u;
}

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const icon = (hero, slot, cls = 'ico') => {
  const svg = ICONS[hero] && ICONS[hero][slot];
  if (!svg) return `<span class="${cls} ${cls}--empty"></span>`;
  return svg.replace('class="sf-ico"', `class="sf-ico ${cls}"`);
};

